"""Write manuscript/figures/geometry.tex (TikZ body, unit disk = radius R tikz units)."""
import math, pathlib

alpha = math.pi * (3 - math.sqrt(5)) / 2  # golden angle
a, Q, R = math.cos(alpha), math.sin(alpha), 4.0
n_chords, r, w = 12, 0.80, 0.07  # x radius; tube half-width (exaggerated)
d = math.acos(a / r)
theta = [(2 * j + 1) * alpha for j in range(n_chords)]
# chord whose normal is nearest 55 degrees carries x and the tube
J = min(range(n_chords), key=lambda j: abs((theta[j] % (2 * math.pi)) - math.radians(55)))
phi = theta[J] + d
P = lambda rad, ang: (R * rad * math.cos(ang), R * rad * math.sin(ang))
f = lambda p: f"({p[0]:.4f},{p[1]:.4f})"
deg = lambda t: math.degrees(t) % 360

L = [
"% CAPTION (for \\caption in sections/dephasing.tex): Unit disk with the caustic circle of radius a = cos(alpha)",
"% (golden alpha), twelve chords of the orbit, and a point z at radius r > a. The two tangent lines from z to the caustic",
"% touch it in the directions phi -+ d(r), d(r) = arccos(a/r): the two angular branches. The solid chord lies on one branch;",
"% the dashed line is the other. The shaded stadium is the tube of half-width w around that chord (w exaggerated).",
f"% generated by make_geometry.py; alpha={alpha:.6f}, a={a:.6f}, r={r}, chord j={J}"]
L.append(r"\draw[thick] (0,0) circle (%g);" % R)
L.append(r"\draw[gray] (0,0) circle (%.4f);" % (R * a))
for j in range(n_chords):
    p0, p1 = P(1, 2 * j * alpha), P(1, 2 * (j + 1) * alpha)
    if j != J:
        L.append(rf"\draw[gray!70, line width=0.35pt] {f(p0)} -- {f(p1)};")
# tube (stadium) around chord J: rectangle plus two end discs
p0, p1 = P(1, 2 * J * alpha), P(1, 2 * (J + 1) * alpha)
tau = theta[J]; nx, ny = math.cos(tau), math.sin(tau); wr = w * R
cs = [(p0[0] + wr * nx, p0[1] + wr * ny), (p1[0] + wr * nx, p1[1] + wr * ny),
      (p1[0] - wr * nx, p1[1] - wr * ny), (p0[0] - wr * nx, p0[1] - wr * ny)]
L.append(r"\fill[gray!25] " + " -- ".join(f(c) for c in cs) + " -- cycle;")
L.append(rf"\fill[gray!25] {f(p0)} circle ({wr:.4f}); \fill[gray!25] {f(p1)} circle ({wr:.4f});")
L.append(rf"\draw[thick] {f(p0)} -- {f(p1)};")
# point x, tangent branches
x = P(r, phi); Tm = P(a, phi - d); Tp = P(a, phi + d)
t = (Tp[0] - x[0], Tp[1] - x[1]); tl = math.hypot(*t); t = (t[0] / tl, t[1] / tl)
b = x[0] * t[0] + x[1] * t[1]; s_ = -b + math.sqrt(b * b - (x[0] ** 2 + x[1] ** 2 - R * R))
far = (x[0] + s_ * t[0], x[1] + s_ * t[1])
L.append(rf"\draw[dashed] {f(x)} -- {f(far)};")
lab = dict(font=r"\small", fill="white", inner="1pt")
for ang, name in ((phi - d, r"\varphi-d(r)"), (phi, r"\varphi"), (phi + d, r"\varphi+d(r)")):
    sty = "gray, densely dotted" if name == r"\varphi" else "gray"
    L.append(rf"\draw[{sty}] (0,0) -- {f(P(1.0, ang))};")
    anc = "east" if math.cos(ang) < -0.2 else ("west" if math.cos(ang) > 0.2 else "south")
    L.append(rf"\node[font=\small, inner sep=2pt, anchor={anc}] at {f(P(1.02, ang))} {{${name}$}};")
for T in (Tm, Tp):
    L.append(rf"\fill {f(T)} circle (1.3pt);")
L.append(rf"\fill {f(x)} circle (1.8pt);")
L.append(rf"\node[font=\small, fill=white, inner sep=1pt] at {f(P(r + 0.07, phi + 0.07))} {{$z$}};")
# angle arcs and labels
ra = 0.62 * R
L.append(rf"\draw[->] {f(P(0.62, phi-d))} arc[start angle={deg(phi-d):.3f}, end angle={deg(phi):.3f}, radius={ra:.4f}];")
L.append(rf"\draw[->] {f(P(0.62, phi))} arc[start angle={deg(phi):.3f}, end angle={deg(phi+d):.3f}, radius={ra:.4f}];")
for sgn in (-1, 1):
    L.append(rf"\node[font=\small, fill=white, inner sep=1pt] at {f(P(0.62, phi + sgn * d / 2))} {{$d(r)$}};")
# a and r
L.append(rf"\node[font=\small, fill=white, inner sep=1pt] at {f(P(a * 0.5, phi + d))} {{$a$}};")
L.append(rf"\node[font=\small, fill=white, inner sep=1pt] at {f(P(0.38, phi))} {{$r$}};")
# w marker at 0.55 along the chord
m = (p0[0] * 0.8 + p1[0] * 0.2, p0[1] * 0.8 + p1[1] * 0.2)
m2 = (m[0] + wr * nx, m[1] + wr * ny)
L.append(rf"\draw[<->, line width=0.4pt] {f(m)} -- {f(m2)};")
L.append(rf"\node[font=\small, fill=white, inner sep=1pt] at {f((m[0] + (wr + 0.3) * nx, m[1] + (wr + 0.3) * ny))} {{$w$}};")
pathlib.Path(__file__).with_name("figures").joinpath("geometry.tex").write_text("\n".join(L) + "\n")
